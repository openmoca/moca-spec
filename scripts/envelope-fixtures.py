#!/usr/bin/env python3
"""Writes the encrypted-package (envelope) fixtures in conformance/fixtures/envelopes/.

Run once, by hand, with the reference Go age CLI (age 1.3 or later, with
age-plugin-batchpass) on the PATH:

    python3 scripts/envelope-fixtures.py

The output is committed as fixed bytes. It is never regenerated by
`npm run refresh:derived`: age encryption is randomised, so a new run gives new
bytes, and the corpus expectations only hold for the committed ones.

Every encrypted file is made by the reference age CLI, never by MOCA code. The
failure fixtures are byte or text edits of those files. Each fixture is then
checked with `age --decrypt`: the good ones decrypt to the inner archive, and
the corrupt ones fail.

The keys in conformance/fixtures/envelopes/keys/ and the passphrases below are
INSECURE test values, published on purpose. Never use them for anything real.
"""
import json
import os
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "conformance" / "fixtures"
OUT = ROOT / "envelopes"
KEYS = OUT / "keys"
PASSPHRASE = "moca-conformance-INSECURE-passphrase"
WRONG_PASSPHRASE = "moca-conformance-INSECURE-wrong"
FIXED_TIME = (1980, 1, 1, 0, 0, 0)


def run(args, **kw):
    return subprocess.run(args, check=True, capture_output=True, **kw)


def pack(directory: Path, compression=zipfile.ZIP_DEFLATED) -> bytes:
    """A .moca archive of a package directory: regular files, sorted, fixed times."""
    files = sorted(p for p in directory.rglob("*") if p.is_file() and not any(part.startswith(".") for part in p.relative_to(directory).parts))
    with tempfile.TemporaryFile() as f:
        with zipfile.ZipFile(f, "w") as z:
            for p in files:
                info = zipfile.ZipInfo(p.relative_to(directory).as_posix(), FIXED_TIME)
                info.compress_type = compression
                z.writestr(info, p.read_bytes())
        f.seek(0)
        return f.read()


def age_x25519(plain: bytes, recipient: str) -> bytes:
    return run(["age", "--encrypt", "-r", recipient], input=plain).stdout


def age_scrypt(plain: bytes, passphrase: str, work_factor: int) -> bytes:
    env = {**os.environ, "AGE_PASSPHRASE": passphrase, "AGE_PASSPHRASE_WORK_FACTOR": str(work_factor)}
    return run(["age", "--encrypt", "-j", "batchpass"], input=plain, env=env).stdout


def split_header(age_file: bytes) -> tuple[bytes, bytes]:
    """The header (up to and including the MAC line) and the payload."""
    end = age_file.index(b"\n--- ") + 1
    end = age_file.index(b"\n", end) + 1
    return age_file[:end], age_file[end:]


def envelope(name: str, entries: dict[str, bytes], stored: tuple[str, ...] = ("package.age", "index.age")) -> None:
    with zipfile.ZipFile(OUT / f"{name}.moca.enc", "w") as z:
        for entry, data in entries.items():
            info = zipfile.ZipInfo(entry, FIXED_TIME)
            info.compress_type = zipfile.ZIP_STORED if entry in stored else zipfile.ZIP_DEFLATED
            z.writestr(info, data)


def marker(outline: dict | None, fmt: str = "moca-enc-v1") -> bytes:
    doc: dict = {"format": fmt}
    if outline is not None:
        doc["outline"] = outline
    return (json.dumps(doc, indent=2, ensure_ascii=False) + "\n").encode()


def keypair(name: str) -> str:
    path = KEYS / f"INSECURE-{name}.txt"
    if not path.exists():
        run(["age-keygen", "-o", str(path)])
    text = path.read_text()
    return next(line.split(": ", 1)[1] for line in text.splitlines() if line.startswith("# public key: "))


def check(name: str, expect_ok: bool, plain: bytes | None = None, identity: str | None = None, passphrase: str | None = None) -> None:
    with zipfile.ZipFile(OUT / f"{name}.moca.enc") as z:
        data = z.read("package.age")
    args = ["age", "--decrypt"]
    env = dict(os.environ)
    if identity:
        args += ["-i", str(KEYS / f"INSECURE-{identity}.txt")]
    if passphrase:
        args += ["-j", "batchpass"]
        env["AGE_PASSPHRASE"] = passphrase
    out = subprocess.run(args, input=data, capture_output=True, env=env)
    ok = out.returncode == 0
    if ok != expect_ok or (ok and plain is not None and out.stdout != plain):
        sys.exit(f"{name}: age --decrypt {'succeeded' if ok else 'failed'}, expected {'success' if expect_ok else 'failure'}: {out.stderr.decode()}")
    print(f"ok   {name}  (age --decrypt {'decrypts' if ok else 'refuses'})")


def main() -> None:
    OUT.mkdir(exist_ok=True)
    KEYS.mkdir(exist_ok=True)
    test = keypair("test")
    keypair("other")

    minimal = pack(ROOT / "valid-minimal")
    minimal_outline = {"id": "https://example.com/conformance/minimal", "version": "1.0.0", "title": "Fixture"}
    manifest = json.loads((ROOT / "valid-minimal" / "moca.json").read_text())
    assert {k: manifest[k] for k in minimal_outline} == minimal_outline, "valid-minimal's manifest changed; update the outline"

    procedure = ROOT / "structure-procedure"
    procedure_manifest = json.loads((procedure / "moca.json").read_text())
    procedure_outline = {k: procedure_manifest[k] for k in ("id", "version", "title")}
    structure = (procedure / "structure.ttl").read_bytes()

    # A package over 64 KiB, so its payload has two age chunks, and over the limit case's maxBytes once inflated.
    large = ROOT / "envelope-large"
    large_manifest = json.loads((large / "moca.json").read_text())
    large_outline = {k: large_manifest[k] for k in ("id", "version", "title")}

    x25519 = age_x25519(minimal, test)
    scrypt = age_scrypt(minimal, PASSPHRASE, 10)

    # Good envelopes.
    envelope("x25519", {"moca-enc.json": marker(minimal_outline), "package.age": x25519})
    envelope("passphrase", {"moca-enc.json": marker(minimal_outline), "package.age": scrypt})
    envelope("no-outline", {"moca-enc.json": marker(None), "package.age": age_x25519(minimal, test)})
    envelope("structure", {"moca-enc.json": marker(procedure_outline), "outline/structure.ttl": structure, "package.age": age_x25519(pack(procedure), test)})
    envelope("large", {"moca-enc.json": marker(large_outline), "package.age": age_x25519(pack(large), test)})

    # E003: payload damaged after encryption.
    stored_large = age_x25519(pack(large, zipfile.ZIP_STORED), test)
    header, payload = split_header(stored_large)
    chunk = 64 * 1024 + 16
    assert len(payload) > 16 + chunk, "the large package must give at least two chunks"
    envelope("truncated", {"moca-enc.json": marker(large_outline), "package.age": header + payload[: 16 + chunk]})
    header, payload = split_header(x25519)
    flipped = bytearray(payload)
    flipped[len(flipped) // 2] ^= 0x01
    envelope("flipped-byte", {"moca-enc.json": marker(minimal_outline), "package.age": header + bytes(flipped)})

    # E004: an outline that does not match what is inside.
    envelope("outline-mismatch", {"moca-enc.json": marker({**minimal_outline, "title": "Another title"}), "package.age": x25519})
    envelope("structure-mismatch", {"moca-enc.json": marker(procedure_outline), "outline/structure.ttl": structure + b"# changed\n", "package.age": age_x25519(pack(procedure), test)})

    # E005: the entry set or the marker.
    envelope("extra-entry", {"moca-enc.json": marker(minimal_outline), "package.age": x25519, "notes.txt": b"not allowed\n"})
    envelope("missing-package", {"moca-enc.json": marker(minimal_outline)})
    envelope("unknown-format", {"moca-enc.json": marker(minimal_outline, "moca-enc-v2"), "package.age": x25519})
    envelope("both-markers", {"moca-enc.json": marker(minimal_outline), "moca.json": (ROOT / "valid-minimal" / "moca.json").read_bytes(), "package.age": x25519})
    envelope("deflated-package", {"moca-enc.json": marker(minimal_outline), "package.age": x25519}, stored=())

    # E006: the age header. An scrypt stanza beside an X25519 one, and a work factor over 20.
    x_header, x_payload = split_header(x25519)
    s_header, _ = split_header(scrypt)
    s_stanza = s_header[s_header.index(b"-> scrypt"): s_header.index(b"\n--- ") + 1]
    mixed = x_header.replace(b"\n--- ", b"\n" + s_stanza + b"--- ", 1)
    envelope("scrypt-not-alone", {"moca-enc.json": marker(minimal_outline), "package.age": mixed + x_payload})
    envelope("work-factor", {"moca-enc.json": marker(minimal_outline), "package.age": age_scrypt(minimal, PASSPHRASE, 21)})

    for name in ("x25519", "no-outline", "outline-mismatch", "extra-entry", "unknown-format", "both-markers", "deflated-package"):
        check(name, True, minimal, identity="test")
    check("structure", True, pack(procedure), identity="test")
    check("structure-mismatch", True, identity="test")
    check("large", True, pack(large), identity="test")
    check("passphrase", True, minimal, passphrase=PASSPHRASE)
    check("passphrase", False, passphrase=WRONG_PASSPHRASE)
    check("x25519", False, identity="other")
    check("truncated", False, identity="test")
    check("flipped-byte", False, identity="test")
    check("scrypt-not-alone", False, identity="test")
    # age itself accepts work factors up to 22; a MOCA Reader refuses anything over 20 by default.
    check("work-factor", True, minimal, passphrase=PASSPHRASE)



def index_fixtures() -> None:
    """The envelopes with an index.age (encrypted packages §6), added in 0.7.0 WP6 without touching the others.

    package.age is the committed x25519 fixture's, byte for byte. index.age is the Zip form of the valid-minimal
    sidecar (fixtures/sidecars/valid), encrypted by the Go age CLI to the test key.
    """
    test = keypair("test")
    with zipfile.ZipFile(OUT / "x25519.moca.enc") as z:
        x25519 = z.read("package.age")
        marker_bytes = z.read("moca-enc.json")
    root = ROOT / "sidecars" / "valid"
    with tempfile.TemporaryFile() as f:
        with zipfile.ZipFile(f, "w") as z:
            for p in sorted(p for p in root.rglob("*") if p.is_file()):
                info = zipfile.ZipInfo(p.relative_to(root).as_posix(), FIXED_TIME)
                info.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(info, p.read_bytes())
        f.seek(0)
        sidecar = f.read()
    index_age = age_x25519(sidecar, test)
    envelope("with-index", {"moca-enc.json": marker_bytes, "package.age": x25519, "index.age": index_age})
    envelope("with-index-deflated", {"moca-enc.json": marker_bytes, "package.age": x25519, "index.age": index_age}, stored=("package.age",))
    header, payload = split_header(index_age)
    flipped = bytearray(payload)
    flipped[len(flipped) // 2] ^= 0x01
    envelope("with-index-corrupt", {"moca-enc.json": marker_bytes, "package.age": x25519, "index.age": header + bytes(flipped)})
    out = subprocess.run(["age", "--decrypt", "-i", str(KEYS / "INSECURE-test.txt")], input=index_age, capture_output=True)
    if out.returncode != 0 or out.stdout != sidecar:
        sys.exit("with-index: age --decrypt does not give the sidecar back")
    print("ok   with-index, with-index-deflated, with-index-corrupt  (index.age decrypts to the sidecar)")


if __name__ == "__main__":
    # `--only index` writes only the index.age fixtures, so the committed envelopes are never re-encrypted.
    if sys.argv[1:] == ["--only", "index"]:
        index_fixtures()
    else:
        main()
        index_fixtures()
